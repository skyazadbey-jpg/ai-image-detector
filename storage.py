"""Private PostgreSQL storage with an explicit SQLite development fallback.

A failed configured PostgreSQL connection never falls back to an empty SQLite
database. Credentials and database rows must never be logged.
"""
import os
import sqlite3
from pathlib import Path

SCHEMA = 'detector_private'


class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        # Only the app's fixed SQL uses this adapter, never user-provided SQL.
        if 'INSERT OR IGNORE INTO guest_trials' in sql:
            sql = sql.replace('INSERT OR IGNORE', 'INSERT') + ' ON CONFLICT (guest_id) DO NOTHING'
        return self.connection.execute(sql.replace('?', '%s'), params)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def get_db():
    url = os.environ.get('DATABASE_URL', '').strip()
    if url:
        import psycopg
        from psycopg.conninfo import conninfo_to_dict
        try:
            config = conninfo_to_dict(url)
            if not config.get('host') or config.get('sslmode') != 'verify-full':
                raise ValueError('DATABASE_URL requires a host and sslmode=verify-full.')
            certificate = os.environ.get('DATABASE_SSL_ROOT_CERT')
            if certificate:
                config['sslrootcert'] = certificate
            connection = psycopg.connect(**config, connect_timeout=8, prepare_threshold=None,
                row_factory=row_factory)
            connection.execute("SET search_path TO detector_private")
            connection.execute("SET statement_timeout TO '8000ms'")
            connection.execute("SET lock_timeout TO '3000ms'")
            return PostgresConnection(connection)
        except Exception:
            # libpq exceptions may contain connection parameters; sanitize them.
            raise RuntimeError('Persistent database unavailable or misconfigured.') from None
    path = Path(os.environ.get('DB_PATH', 'users.db')).resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=8)
    connection.row_factory = sqlite3.Row
    connection.execute('PRAGMA busy_timeout=8000')
    connection.execute('PRAGMA journal_mode=WAL')
    connection.execute('PRAGMA foreign_keys=ON')
    return connection


def initialize():
    conn = get_db()
    postgres = isinstance(conn, PostgresConnection)
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    real = 'DOUBLE PRECISION' if postgres else 'REAL'
    try:
        if postgres:
            conn.execute('CREATE SCHEMA IF NOT EXISTS detector_private')
            conn.execute('REVOKE ALL ON SCHEMA detector_private FROM PUBLIC')
        conn.execute(f'''CREATE TABLE IF NOT EXISTS users (
            id {identity}, email TEXT UNIQUE NOT NULL, password_hash TEXT,
            google_id TEXT, is_verified INTEGER DEFAULT 0, is_pro INTEGER DEFAULT 0,
            credits INTEGER DEFAULT 3, otp_code TEXT, otp_expires {real}, created_at {real})''')
        if postgres:
            conn.execute('ALTER TABLE users ADD COLUMN IF NOT EXISTS is_pro INTEGER DEFAULT 0')
            conn.execute('ALTER TABLE users ADD COLUMN IF NOT EXISTS credits INTEGER DEFAULT 3')
        else:
            columns = {row['name'] for row in conn.execute('PRAGMA table_info(users)').fetchall()}
            for name, definition in [('is_pro', 'INTEGER DEFAULT 0'), ('credits', 'INTEGER DEFAULT 3')]:
                if name not in columns:
                    conn.execute(f'ALTER TABLE users ADD COLUMN {name} {definition}')
        conn.execute(f'''CREATE TABLE IF NOT EXISTS feedback (
            id {identity}, image_hash TEXT NOT NULL, ai_score {real} NOT NULL,
            predicted TEXT NOT NULL, actual TEXT NOT NULL, mode TEXT DEFAULT 'general',
            created_at {real} NOT NULL)''')
        conn.execute('CREATE INDEX IF NOT EXISTS idx_feedback_hash ON feedback(image_hash)')
        conn.execute('CREATE INDEX IF NOT EXISTS idx_feedback_created ON feedback(created_at)')
        conn.execute('CREATE TABLE IF NOT EXISTS guest_trials (guest_id TEXT PRIMARY KEY, used INTEGER NOT NULL DEFAULT 0)')
        if postgres:
            # Private schema is not an exposed Supabase Data API schema. RLS adds
            # protection against accidental grants; backend owner bypasses RLS.
            for table in ('users', 'feedback', 'guest_trials'):
                conn.execute(f'ALTER TABLE {table} ENABLE ROW LEVEL SECURITY')
                conn.execute(f'REVOKE ALL ON TABLE {table} FROM PUBLIC')
        conn.commit()
    except Exception:
        conn.rollback()
        raise RuntimeError('Database schema initialization failed.') from None
    finally:
        conn.close()


def check():
    conn = get_db()
    try:
        conn.execute('SELECT 1').fetchone()
        return {'available': True, 'backend': 'postgresql' if isinstance(conn, PostgresConnection) else 'sqlite',
                'external_storage_configured': isinstance(conn, PostgresConnection)}
    finally:
        conn.close()
